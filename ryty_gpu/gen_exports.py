# Generates the export thunks that let Ryty's loader find a shadGT HLE library's functions by NID.
# Each thunk jumps through g_ryty_export_targets, which the library's entry code fills from the
# LIB_FUNCTION registrations once the library is initialized.
#
# Usage: python gen_exports.py <shadGT src dir> <output dir> <library file name> <source>...
import os
import re
import sys


def main():
    src, out, library = sys.argv[1], sys.argv[2], sys.argv[3]
    sources = sys.argv[4:]
    nids = []
    for rel in sources:
        text = open(os.path.join(src, rel), encoding="utf-8").read()
        for nid in re.findall(r'LIB_FUNCTION\("([^"]+)"', text):
            if nid not in nids:
                nids.append(nid)

    cpp = [
        "// Generated by ryty_gpu/gen_exports.py; do not edit.",
        "#include <cstdint>",
        "",
        'extern "C" {',
        f"void* g_ryty_export_targets[{len(nids)}];",
        f"extern const char* const g_ryty_export_nids[{len(nids)}] = {{",
    ]
    cpp += [f'    "{nid}",' for nid in nids]
    cpp += [
        "};",
        f"extern const unsigned g_ryty_export_count = {len(nids)};",
        "}",
        "",
        "__asm__(",
        '    ".att_syntax prefix\\n"',
        '    ".text\\n"',
    ]
    for index in range(len(nids)):
        cpp += [
            f'    ".globl ryty_export_{index}\\n"',
            f'    "ryty_export_{index}:\\n"',
            f'    "    leaq g_ryty_export_targets+{index * 8}(%rip), %r11\\n"',
            '    "    jmp ryty_export_dispatch\\n"',
        ]
    cpp.append(");")

    definition = [f"LIBRARY {library}", "EXPORTS"]
    definition += [f'    "{nid}"=ryty_export_{index}' for index, nid in enumerate(nids)]

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "ryty_exports.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(cpp) + "\n")
    with open(os.path.join(out, "ryty_exports.def"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(definition) + "\n")
    print(f"{library}: {len(nids)} exports")


if __name__ == "__main__":
    main()
